#!/usr/bin/env python3
"""
Converts G Developments Primary ATS CSV (and optional Cash/Payment schedule JSON)
into structured data/newkairo_inventory.json for the web portal.

Usage:
    python3 scripts/sync_ats_csv.py
    python3 scripts/sync_ats_csv.py data/primary_ats_newkairo.csv data/newkairo_inventory.json
"""

import csv
import json
import sys
from pathlib import Path
from collections import Counter


def parse_bool(val: str) -> bool:
    return str(val).strip().lower() == "true"


def parse_float(val: str):
    v = str(val).strip().replace(",", "")
    if not v or v.upper() == "N/A":
        return None
    try:
        num = float(v)
        return int(num) if num.is_integer() else round(num, 2)
    except ValueError:
        return None


def parse_ats_csv(csv_path: Path):
    meta = {
        "reportTitle": "Primary ATS NEWKAIRO",
        "asOf": "",
        "generatedBy": "",
        "project": "NEWKAIRO",
        "sourceFile": csv_path.name,
        "cashPricing": {
            "status": "pending_official_sheet",
            "defaultInstallmentPlan": {
                "downPaymentPct": 5,
                "after3MonthsPct": 5,
                "years": 8,
                "quarterlyInstallments": 32,
                "label": "5% Down · 5% After 3 Months · 8 Years Equal Quarterly"
            },
            "estimatedCashDiscountPct": None,
            "note": "Official final payment & cash discount sheet will replace estimated calculations once uploaded."
        }
    }

    rows = []
    with csv_path.open("r", encoding="utf-8-sig", newline="") as f:
        reader = list(csv.reader(f))

    header_idx = None
    for idx, r in enumerate(reader):
        joined = " ".join(cell.strip() for cell in r if cell.strip())
        if "Primary ATS" in joined and not meta["asOf"]:
            meta["reportTitle"] = joined
        if "As of " in joined:
            parts = joined.split("•")
            meta["asOf"] = parts[0].replace("As of ", "").strip()
            if len(parts) > 1:
                meta["generatedBy"] = parts[1].replace("Generated by", "").strip()
        if any("Unit: Unit Number" in cell for cell in r) or any("Gross BUA" in cell for cell in r):
            header_idx = idx
            break

    if header_idx is None:
        raise ValueError("Could not locate header row in ATS CSV.")

    headers = [h.strip() for h in reader[header_idx]]
    col_map = {}
    for i, h in enumerate(headers):
        norm = h.replace("↑", "").replace("↓", "").strip().lower()
        if norm.startswith("phase"):
            col_map["phase"] = i
        elif norm == "unit type":
            col_map["unitType"] = i
        elif "unit number" in norm:
            col_map["unitNumber"] = i
        elif norm == "design":
            col_map["design"] = i
        elif norm == "building":
            col_map["building"] = i
        elif norm == "location":
            col_map["location"] = i
        elif "number of beds" in norm or norm == "beds":
            col_map["beds"] = i
        elif norm == "floor":
            col_map["floor"] = i
        elif norm == "corner":
            col_map["corner"] = i
        elif norm == "passage":
            col_map["passage"] = i
        elif "gross bua" in norm or norm == "bua":
            col_map["bua"] = i
        elif "land area" in norm:
            col_map["landArea"] = i
        elif norm == "garden":
            col_map["garden"] = i
        elif "garden area" in norm:
            col_map["gardenArea"] = i
        elif "total unit price" in norm or norm == "price":
            col_map["totalPrice"] = i
        elif "cash price" in norm:
            col_map["cashPrice"] = i
        elif "finishing" in norm:
            col_map["finishing"] = i
        elif "sub status" in norm or norm == "status":
            col_map["status"] = i

    current_phase = ""
    current_unit_type = ""

    for r in reader[header_idx + 1:]:
        if not any(cell.strip() for cell in r):
            continue

        def get(key):
            idx = col_map.get(key)
            if idx is None or idx >= len(r):
                return ""
            return r[idx].strip()

        phase_val = get("phase")
        type_val = get("unitType")
        unit_num = get("unitNumber")

        if phase_val:
            current_phase = phase_val
        if type_val:
            current_unit_type = type_val
        if not unit_num:
            continue

        bua = parse_float(get("bua"))
        land = parse_float(get("landArea"))
        garden_area = parse_float(get("gardenArea"))
        price = parse_float(get("totalPrice"))
        cash_price = parse_float(get("cashPrice")) if "cashPrice" in col_map else None
        beds_raw = get("beds")
        beds = parse_float(beds_raw)
        if beds is None:
            beds = beds_raw

        location = get("location")
        if location.upper() == "N/A":
            location = ""

        floor = get("floor")
        if floor.upper() == "N/A":
            floor = ""

        # Derive golf/zone sub-cluster for easy filtering
        zone = ""
        if unit_num.startswith("AR-"):
            zone = "Argon Views"
        elif unit_num.startswith("CE-"):
            zone = "Cerium Views"
        elif unit_num.startswith("NE-"):
            zone = "Neon Views"
        elif unit_num.startswith("KR"):
            zone = "Krome / Park"
        elif unit_num.startswith("B"):
            zone = f"Building {get('building')}"

        price_per_sqm = round(price / bua) if (price and bua) else None

        rows.append({
            "phase": current_phase,
            "unitType": current_unit_type,
            "unitNumber": unit_num,
            "design": get("design"),
            "building": get("building"),
            "zone": zone,
            "location": location,
            "beds": beds,
            "floor": floor,
            "corner": parse_bool(get("corner")),
            "passage": parse_bool(get("passage")),
            "bua": bua,
            "landArea": land,
            "hasGarden": parse_bool(get("garden")),
            "gardenArea": garden_area,
            "totalPrice": price,
            "cashPrice": cash_price,
            "pricePerSqm": price_per_sqm,
            "finishing": get("finishing"),
            "status": get("status"),
        })

    # Compute summary analytics
    phases = {}
    for u in rows:
        p = u["phase"]
        if p not in phases:
            phases[p] = {
                "phase": p,
                "totalUnits": 0,
                "availableUnits": 0,
                "minPrice": None,
                "maxPrice": None,
                "unitTypes": set(),
            }
        phases[p]["totalUnits"] += 1
        if u["status"] in ("Available", "Ready for Reservation"):
            phases[p]["availableUnits"] += 1
        if u["totalPrice"]:
            if phases[p]["minPrice"] is None or u["totalPrice"] < phases[p]["minPrice"]:
                phases[p]["minPrice"] = u["totalPrice"]
            if phases[p]["maxPrice"] is None or u["totalPrice"] > phases[p]["maxPrice"]:
                phases[p]["maxPrice"] = u["totalPrice"]
        phases[p]["unitTypes"].add(u["unitType"])

    phase_summary = []
    for p_data in phases.values():
        p_data["unitTypes"] = sorted(p_data["unitTypes"])
        phase_summary.append(p_data)

    status_counts = Counter(u["status"] for u in rows)
    prices = [u["totalPrice"] for u in rows if u["totalPrice"]]

    payload = {
        "meta": meta,
        "summary": {
            "totalUnits": len(rows),
            "statusCounts": dict(status_counts),
            "minPrice": min(prices) if prices else None,
            "maxPrice": max(prices) if prices else None,
            "phases": phase_summary,
        },
        "units": rows,
    }
    return payload


def main():
    root = Path(__file__).resolve().parent.parent
    csv_path = Path(sys.argv[1]) if len(sys.argv) > 1 else root / "data" / "primary_ats_newkairo.csv"
    out_path = Path(sys.argv[2]) if len(sys.argv) > 2 else root / "data" / "newkairo_inventory.json"

    payload = parse_ats_csv(csv_path)
    out_path.parent.mkdir(parents=True, exist_ok=True)
    out_path.write_text(json.dumps(payload, indent=2, ensure_ascii=False), encoding="utf-8")

    s = payload["summary"]
    print(f"Synced {s['totalUnits']} units -> {out_path}")
    print(f"Statuses: {s['statusCounts']}")
    print(f"Price range: {s['minPrice']:,} EGP -> {s['maxPrice']:,} EGP")
    for ph in s["phases"]:
        print(f"  - {ph['phase']}: {ph['totalUnits']} total ({ph['availableUnits']} available), {ph['minPrice']:,} - {ph['maxPrice']:,} EGP")


if __name__ == "__main__":
    main()
