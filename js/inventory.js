function formatNumber(n) {
  if (n === null || n === undefined || Number.isNaN(Number(n))) return '—';
  return new Intl.NumberFormat('en-EG').format(Math.round(Number(n)));
}

function formatMillions(n) {
  if (!n) return '—';
  return `${(n / 1_000_000).toFixed(2)}M`;
}

function escapeHtml(str = '') {
  return String(str)
    .replace(/&/g, '&amp;')
    .replace(/</g, '&lt;')
    .replace(/>/g, '&gt;')
    .replace(/"/g, '&quot;');
}

function parseCsvRows(text) {
  const rows = [];
  let row = [];
  let cur = '';
  let inQuotes = false;
  for (let i = 0; i < text.length; i++) {
    const ch = text[i];
    const next = text[i + 1];
    if (inQuotes) {
      if (ch === '"' && next === '"') {
        cur += '"';
        i++;
      } else if (ch === '"') {
        inQuotes = false;
      } else {
        cur += ch;
      }
    } else {
      if (ch === '"') {
        inQuotes = true;
      } else if (ch === ',') {
        row.push(cur);
        cur = '';
      } else if (ch === '\n' || ch === '\r') {
        if (ch === '\r' && next === '\n') i++;
        row.push(cur);
        rows.push(row);
        row = [];
        cur = '';
      } else {
        cur += ch;
      }
    }
  }
  if (cur.length > 0 || row.length > 0) {
    row.push(cur);
    rows.push(row);
  }
  return rows;
}

export function parsePrimaryAtsCsvClient(csvText, fileName = 'uploaded_ats.csv') {
  const rawRows = parseCsvRows(csvText);
  let headerIdx = -1;
  let asOf = new Date().toISOString().slice(0, 10);
  let generatedBy = 'Broker Upload';

  for (let i = 0; i < Math.min(rawRows.length, 30); i++) {
    const joined = rawRows[i].map((c) => c.trim()).filter(Boolean).join(' ');
    if (joined.includes('As of ')) {
      const parts = joined.split('•');
      asOf = parts[0].replace('As of ', '').trim();
      if (parts[1]) generatedBy = parts[1].replace('Generated by', '').trim();
    }
    if (rawRows[i].some((c) => c.includes('Unit: Unit Number') || c.includes('Gross BUA') || c.toLowerCase().includes('unit number'))) {
      headerIdx = i;
      break;
    }
  }

  if (headerIdx === -1) {
    throw new Error('Could not find header row (expected "Unit: Unit Number" or "Gross BUA").');
  }

  const headers = rawRows[headerIdx].map((h) => h.replace(/[↑↓]/g, '').trim().toLowerCase());
  const findCol = (pred) => headers.findIndex(pred);
  const idx = {
    phase: findCol((h) => h.startsWith('phase')),
    unitType: findCol((h) => h === 'unit type'),
    unitNumber: findCol((h) => h.includes('unit number')),
    design: findCol((h) => h === 'design'),
    building: findCol((h) => h === 'building'),
    location: findCol((h) => h === 'location'),
    beds: findCol((h) => h.includes('beds')),
    floor: findCol((h) => h === 'floor'),
    corner: findCol((h) => h === 'corner'),
    passage: findCol((h) => h === 'passage'),
    bua: findCol((h) => h.includes('bua')),
    landArea: findCol((h) => h.includes('land area')),
    garden: findCol((h) => h === 'garden'),
    gardenArea: findCol((h) => h.includes('garden area')),
    totalPrice: findCol((h) => h.includes('total unit price') || h === 'price'),
    cashPrice: findCol((h) => h.includes('cash price') || h.includes('cash')),
    finishing: findCol((h) => h.includes('finishing')),
    status: findCol((h) => h.includes('sub status') || h === 'status'),
  };

  const toNum = (v) => {
    const clean = String(v || '').replace(/,/g, '').trim();
    if (!clean || clean.toUpperCase() === 'N/A') return null;
    const n = Number(clean);
    return Number.isFinite(n) ? n : null;
  };

  let curPhase = '';
  let curType = '';
  const units = [];

  for (let r = headerIdx + 1; r < rawRows.length; r++) {
    const line = rawRows[r];
    if (!line || !line.some((c) => c.trim())) continue;
    const get = (k) => (idx[k] >= 0 && idx[k] < line.length ? line[idx[k]].trim() : '');

    if (get('phase')) curPhase = get('phase');
    if (get('unitType')) curType = get('unitType');
    const unitNumber = get('unitNumber');
    if (!unitNumber) continue;

    const bua = toNum(get('bua'));
    const landArea = toNum(get('landArea'));
    const totalPrice = toNum(get('totalPrice'));
    const cashPrice = idx.cashPrice >= 0 ? toNum(get('cashPrice')) : null;
    const beds = toNum(get('beds')) ?? get('beds');

    let zone = '';
    if (unitNumber.startsWith('AR-')) zone = 'Argon Views';
    else if (unitNumber.startsWith('CE-')) zone = 'Cerium Views';
    else if (unitNumber.startsWith('NE-')) zone = 'Neon Views';
    else if (unitNumber.startsWith('KR')) zone = 'Krome / Park';
    else if (get('building')) zone = `Building ${get('building')}`;

    units.push({
      phase: curPhase,
      unitType: curType,
      unitNumber,
      design: get('design'),
      building: get('building'),
      zone,
      location: get('location').toUpperCase() === 'N/A' ? '' : get('location'),
      beds,
      floor: get('floor').toUpperCase() === 'N/A' ? '' : get('floor'),
      corner: get('corner').toLowerCase() === 'true',
      passage: get('passage').toLowerCase() === 'true',
      bua,
      landArea,
      hasGarden: get('garden').toLowerCase() === 'true',
      gardenArea: toNum(get('gardenArea')),
      totalPrice,
      cashPrice,
      pricePerSqm: totalPrice && bua ? Math.round(totalPrice / bua) : null,
      finishing: get('finishing'),
      status: get('status') || 'Available',
    });
  }

  const prices = units.map((u) => u.totalPrice).filter(Boolean);
  const statusCounts = {};
  units.forEach((u) => {
    statusCounts[u.status] = (statusCounts[u.status] || 0) + 1;
  });

  return {
    meta: {
      reportTitle: 'Primary ATS NEWKAIRO',
      asOf,
      generatedBy,
      project: 'NEWKAIRO',
      sourceFile: fileName,
      cashPricing: {
        status: units.some((u) => u.cashPrice) ? 'official_sheet_loaded' : 'pending_official_sheet',
      },
    },
    summary: {
      totalUnits: units.length,
      statusCounts,
      minPrice: prices.length ? Math.min(...prices) : null,
      maxPrice: prices.length ? Math.max(...prices) : null,
    },
    units,
  };
}

