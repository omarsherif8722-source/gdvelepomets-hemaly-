  function computePaymentCell(unit) {
    const price = unit.totalPrice;
    if (!price) return '<span>On Request</span>';
    const mode = payModeEl.value;

    if (mode === 'cash-sim') {
      if (unit.cashPrice) {
        return `<strong class="tabular" style="color:var(--status-available);">${formatNumber(unit.cashPrice)} EGP</strong><span class="unit-sub">Official Cash Price</span>`;
      }
      const disc = Number(cashSlider.value) || 0;
      const est = Math.round(price * (1 - disc / 100));
      return `<strong class="tabular" style="color:var(--gold-hover);">${formatNumber(est)} EGP</strong><span class="unit-sub">Est. at ${disc}% Cash Disc.</span>`;
    }

    const quarters = mode === 'installment-7y' ? 28 : 32;
    const dp5 = Math.round(price * 0.05);
    const quarterly = Math.round((price * 0.9) / quarters);
    return `<strong class="tabular">${formatNumber(dp5)} EGP</strong><span class="unit-sub">5% Down · ${formatNumber(quarterly)} / qtr</span>`;
  }

  function statusClass(status) {
    if (status === 'Available') return 'status-available';
    if (status === 'Ready for Reservation') return 'status-ready';
    return 'status-hold';
  }

  function getFilteredUnits() {
    const units = state.inventory?.units || [];
    const q = searchEl.value.trim().toLowerCase();
    const phase = phaseEl.value;
    const type = typeEl.value;
    const beds = bedsEl.value;
    const status = statusEl.value;

    const filtered = units.filter((u) => {
      if (phase === 'NEON' && !u.phase.includes('NEON VIEWS')) return false;
      else if (phase !== 'ALL' && phase !== 'NEON' && u.phase !== phase) return false;
      if (type !== 'ALL' && u.unitType !== type) return false;
      if (beds !== 'ALL' && String(u.beds) !== beds) return false;
      if (status !== 'ALL' && u.status !== status) return false;
      if (q) {
        const hay = `${u.unitNumber} ${u.building} ${u.design} ${u.zone} ${u.location} ${u.phase} ${u.unitType}`.toLowerCase();
        if (!hay.includes(q)) return false;
      }
      return true;
    });

    const sort = sortEl.value;
    filtered.sort((a, b) => {
      if (sort === 'price-asc') return (a.totalPrice || 0) - (b.totalPrice || 0);
      if (sort === 'price-desc') return (b.totalPrice || 0) - (a.totalPrice || 0);
      if (sort === 'bua-asc') return (a.bua || 0) - (b.bua || 0);
      if (sort === 'bua-desc') return (b.bua || 0) - (a.bua || 0);
      if (sort === 'psqm-asc') return (a.pricePerSqm || 9e9) - (b.pricePerSqm || 9e9);
      return 0;
    });
    return filtered;
  }

